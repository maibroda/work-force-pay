const MAPS: Record<EntryKind, Record<string, EntryModule>> = { page: PAGE_MODULES, action: ACTION_MODULES, api: API_MODULES, job: JOB_MODULES };

/** The module an entry is held to: the core while it is unconfirmed, otherwise what is declared. */
export function effectiveModule(kind: EntryKind, key: string): EntryModule {
  const declared = MAPS[kind][key];
  if (!declared) throw new Error(`${kind} ${key} has no module declared (src/lib/entitlements/entry-modules.ts).`);
  return UNCONFIRMED.has(`${kind} ${key}`) ? "core" : declared;
}
